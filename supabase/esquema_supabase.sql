insert into public.roles_permisos (id_rol, id_permiso)
select r.id_rol, p.id_permiso from public.roles r cross join public.permisos p
where (r.codigo = 'administrador' and p.codigo in
          ('inventario.gestionar', 'usuarios.gestionar', 'mercado.supervisar', 'mercado.consultar', 'perfil.editar'))
   or (r.codigo = 'vendedor' and p.codigo in ('mercado.consultar', 'publicaciones.gestionar', 'ofertas.recibir', 'perfil.editar'))
   or (r.codigo = 'comprador' and p.codigo in ('mercado.consultar', 'ofertas.enviar', 'perfil.editar'))
   or (r.codigo = 'empresa' and p.codigo in ('mercado.consultar', 'ofertas.enviar', 'empresa.gestionar', 'perfil.editar'));

