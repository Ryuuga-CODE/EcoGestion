-- 3. Centro de acopio (módulos originales)
-- ------------------------------------------------------------
create table public.materiales (
    id_material     bigint generated by default as identity primary key,
    nombre          text not null check (length(btrim(nombre)) between 2 and 80),
    categoria       text not null check (categoria in ('Plástico', 'Papel y cartón', 'Vidrio', 'Metal', 'Otros')),
    unidad_medida   text not null check (unidad_medida in ('kg', 'unidades', 'litros')),
    descripcion     text check (descripcion is null or length(descripcion) <= 300),
    fecha_registro  timestamp not null default (now() at time zone 'America/Bogota')
);
create unique index ux_materiales_nombre on public.materiales (lower(nombre));
create index idx_materiales_categoria on public.materiales (categoria);

create table public.recolecciones (
    id_recoleccion  bigint generated by default as identity primary key,
    id_material     bigint not null references public.materiales (id_material) on update cascade on delete restrict,
    id_usuario      bigint not null references public.usuarios (id_usuario) on update cascade on delete restrict,
    cantidad        numeric(14, 2) not null check (cantidad > 0),
    unidad_medida   text not null check (unidad_medida in ('kg', 'unidades', 'litros')),
    fecha           date not null,
    observaciones   text check (observaciones is null or length(observaciones) <= 300),
    fecha_registro  timestamp not null default (now() at time zone 'America/Bogota'),
    constraint chk_recoleccion_enteros check (unidad_medida <> 'unidades' or cantidad = trunc(cantidad))
);
create index idx_recolecciones_fecha on public.recolecciones (fecha);
create index idx_recolecciones_material on public.recolecciones (id_material);

create table public.movimientos (
    id_movimiento   bigint generated by default as identity primary key,
    id_material     bigint not null references public.materiales (id_material) on update cascade on delete restrict,
    id_recoleccion  bigint unique references public.recolecciones (id_recoleccion) on update cascade on delete restrict,
    id_usuario      bigint not null references public.usuarios (id_usuario) on update cascade on delete restrict,
    tipo            text not null check (tipo in ('Entrada', 'Salida')),
    cantidad        numeric(14, 2) not null check (cantidad > 0),
    unidad_medida   text not null check (unidad_medida in ('kg', 'unidades', 'litros')),
    fecha           date not null,
    observaciones   text check (observaciones is null or length(observaciones) <= 300),
    fecha_registro  timestamp not null default (now() at time zone 'America/Bogota'),
    constraint chk_movimiento_origen check ((tipo = 'Entrada' and id_recoleccion is not null)
                                         or (tipo = 'Salida' and id_recoleccion is null)),
    constraint chk_movimiento_enteros check (unidad_medida <> 'unidades' or cantidad = trunc(cantidad))
);
create index idx_movimientos_material on public.movimientos (id_material);
create index idx_movimientos_fecha on public.movimientos (fecha);

