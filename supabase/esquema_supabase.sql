create or replace function public.texto_limpio(p text) returns text
language sql immutable as $$ select nullif(regexp_replace(btrim(coalesce(p, '')), '\s+', ' ', 'g'), '') $$;

create or replace function public.hoy_bogota() returns date
language sql stable as $$ select (now() at time zone 'America/Bogota')::date $$;

create or replace function public.ahora_bogota() returns timestamp
language sql stable as $$ select (now() at time zone 'America/Bogota') $$;

create or replace function public.existencia_material(p_id bigint) returns numeric
language sql stable security definer set search_path = public as $$
    select coalesce(sum(case when tipo = 'Entrada' then cantidad else -cantidad end), 0)
    from movimientos where id_material = p_id
$$;

-- 1234.5 → '1234.5' (para mensajes de error)
create or replace function public.cantidad_texto(p numeric) returns text
language sql immutable as $$ select rtrim(rtrim(to_char(greatest(coalesce(p, 0), 0), 'FM999999999990.00'), '0'), '.') $$;

-- Lo aprobado a empresas que todavía no se entrega (queda reservado)
create or replace function public.comprometido_material(p_id bigint) returns numeric
language sql stable security definer set search_path = public as $$
    select coalesce(sum(cantidad), 0) from pedidos_empresa where id_material = p_id and estado = 'Aprobado'
$$;

