-- 6. Triggers de integridad (protegen la base aunque falle la app)
-- ------------------------------------------------------------
create or replace function public.trg_movimiento_validar() returns trigger
language plpgsql set search_path = public as $$
declare
    v_material materiales%rowtype;
begin
    select * into v_material from materiales where id_material = new.id_material;
    if v_material.unidad_medida is distinct from new.unidad_medida then
        raise exception 'La unidad de medida no coincide con la del material.';
    end if;
    if v_material.codigo_municipio is distinct from new.codigo_municipio then
        raise exception 'El material pertenece a otro municipio.';
    end if;
    if new.tipo = 'Salida' and new.cantidad > existencia_material(new.id_material) + 0.000001 then
        raise exception 'Stock insuficiente para registrar la salida.';
    end if;
    return new;
end $$;
create trigger trg_movimiento_validar before insert on public.movimientos
    for each row execute function public.trg_movimiento_validar();

create or replace function public.trg_solicitud_estado() returns trigger
language plpgsql set search_path = public as $$
begin
    if new.estado <> old.estado and not (
           (old.estado = 'Pendiente' and new.estado in ('Asignada', 'Cancelada', 'Rechazada'))
        or (old.estado = 'Asignada'  and new.estado in ('Pendiente', 'Recolectada', 'Cancelada', 'Rechazada'))) then
        raise exception 'Cambio de estado de la solicitud no permitido.';
    end if;
    return new;
end $$;
create trigger trg_solicitud_estado before update of estado on public.solicitudes_recoleccion
    for each row execute function public.trg_solicitud_estado();

create or replace function public.trg_pedido_estado() returns trigger
language plpgsql set search_path = public as $$
begin
    if new.estado <> old.estado and not (
           (old.estado = 'Pendiente' and new.estado in ('Aprobado', 'Rechazado', 'Cancelado'))
        or (old.estado = 'Aprobado'  and new.estado in ('Entregado', 'Rechazado', 'Cancelado'))) then
        raise exception 'Cambio de estado del pedido no permitido.';
    end if;
    return new;
end $$;
create trigger trg_pedido_estado before update of estado on public.pedidos_empresa
    for each row execute function public.trg_pedido_estado();

