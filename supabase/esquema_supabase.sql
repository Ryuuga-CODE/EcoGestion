create or replace function public.enviar_oferta(
    p_id_publicacion bigint, p_cantidad numeric, p_precio numeric, p_mensaje text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('ofertas.enviar');
    v_pub publicaciones%rowtype;
    v_id bigint;
begin
    select * into v_pub from publicaciones where id_publicacion = p_id_publicacion;
    if not found or v_pub.estado <> 'Activa' then
        raise exception 'La publicación no está disponible para recibir ofertas.';
    end if;
    if not exists (select 1 from perfiles p join roles r on r.id_rol = p.id_rol
                    where p.id_usuario = v_pub.id_vendedor and p.activo = 1 and r.codigo = 'vendedor') then
        raise exception 'La publicación no está disponible para recibir ofertas.';
    end if;
    if v_pub.id_vendedor = v_yo then raise exception 'No puedes ofertar por tu propia publicación.'; end if;
    if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
    if v_pub.unidad = 'unidades' and p_cantidad <> trunc(p_cantidad) then
        raise exception 'Para unidades, la cantidad debe ser un número entero.';
    end if;
    if p_cantidad > v_pub.cantidad_disponible then
        raise exception 'La cantidad solicitada supera la cantidad disponible.';
    end if;
    if p_precio is null or p_precio <= 0 then raise exception 'El precio debe ser mayor que cero.'; end if;
    if exists (select 1 from ofertas where id_publicacion = p_id_publicacion and id_comprador = v_yo and estado = 'Pendiente') then
        raise exception 'Ya tienes una oferta pendiente para esta publicación.';
    end if;
    insert into ofertas (id_publicacion, id_comprador, cantidad, precio_unitario, mensaje)
    values (p_id_publicacion, v_yo, round(p_cantidad, 2), round(p_precio, 2), texto_limpio(p_mensaje))
    returning id_oferta into v_id;
    return v_id;
end $$;

-- aceptar | rechazar | cancelar | completar
create or replace function public.responder_oferta(p_id bigint, p_accion text) returns text
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := yo();
    v_oferta ofertas%rowtype;
    v_pub publicaciones%rowtype;
    v_es_vendedor boolean;
    v_es_comprador boolean;
begin
    if v_yo is null then raise exception 'No tienes permiso para realizar esta acción.'; end if;
    select * into v_oferta from ofertas where id_oferta = p_id for update;
    if not found then raise exception 'La oferta ya no existe.'; end if;
    select * into v_pub from publicaciones where id_publicacion = v_oferta.id_publicacion for update;
    v_es_vendedor := v_pub.id_vendedor = v_yo and tiene_permiso('ofertas.recibir');
    v_es_comprador := v_oferta.id_comprador = v_yo and tiene_permiso('ofertas.enviar');

    if p_accion = 'aceptar' then
        if not v_es_vendedor then raise exception 'Solo el vendedor puede aceptar esta oferta.'; end if;
        if v_oferta.estado <> 'Pendiente' then raise exception 'La oferta ya no está pendiente.'; end if;
        if v_pub.estado = 'Retirada' then raise exception 'La publicación fue retirada del mercado.'; end if;
        if v_oferta.cantidad > v_pub.cantidad_disponible then
            raise exception 'La cantidad solicitada supera lo disponible (% %). Rechaza la oferta o actualiza la publicación.',
                trim(to_char(v_pub.cantidad_disponible, 'FM999999999990.##')), v_pub.unidad;
        end if;
        update publicaciones
           set cantidad_disponible = cantidad_disponible - v_oferta.cantidad,
               estado = case when cantidad_disponible - v_oferta.cantidad <= 0 then 'Agotada' else estado end,
               fecha_actualizacion = ahora_bogota()
         where id_publicacion = v_pub.id_publicacion;
        update ofertas set estado = 'Aceptada', fecha_respuesta = ahora_bogota() where id_oferta = p_id;
        insert into transacciones (id_oferta) values (p_id);
        return 'Aceptada';

    elsif p_accion = 'rechazar' then
        if not v_es_vendedor then raise exception 'Solo el vendedor puede rechazar esta oferta.'; end if;
        if v_oferta.estado <> 'Pendiente' then raise exception 'La oferta ya no está pendiente.'; end if;
        update ofertas set estado = 'Rechazada', fecha_respuesta = ahora_bogota() where id_oferta = p_id;
        return 'Rechazada';

    elsif p_accion = 'cancelar' then
        if not (v_es_vendedor or v_es_comprador) then raise exception 'No puedes cancelar esta oferta.'; end if;
        if v_oferta.estado = 'Pendiente' then
            if not v_es_comprador then raise exception 'El vendedor debe rechazar la oferta, no cancelarla.'; end if;
            update ofertas set estado = 'Cancelada', fecha_respuesta = ahora_bogota() where id_oferta = p_id;
        elsif v_oferta.estado = 'Aceptada' then
            update publicaciones
               set cantidad_disponible = cantidad_disponible + v_oferta.cantidad,
                   estado = case when estado = 'Agotada' then 'Activa' else estado end,
                   fecha_actualizacion = ahora_bogota()
             where id_publicacion = v_pub.id_publicacion;
            update transacciones set estado = 'Cancelada', fecha_cierre = ahora_bogota() where id_oferta = p_id;
            update ofertas set estado = 'Cancelada' where id_oferta = p_id;
        else
            raise exception 'La oferta ya no se puede cancelar.';
        end if;
        return 'Cancelada';

    elsif p_accion = 'completar' then
        if not v_es_vendedor then raise exception 'Solo el vendedor puede completar la operación.'; end if;
        if v_oferta.estado <> 'Aceptada' then raise exception 'Solo se completan operaciones aceptadas.'; end if;
        update ofertas set estado = 'Completada' where id_oferta = p_id;
        update transacciones set estado = 'Completada', fecha_cierre = ahora_bogota() where id_oferta = p_id;
        return 'Completada';
    end if;
    raise exception 'Acción no válida.';
end $$;

