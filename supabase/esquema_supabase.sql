-- ============================================================
-- EcoGestión · Base central en Supabase (PostgreSQL)
-- Versión 5: gestión municipal de residuos aprovechables
-- ============================================================
-- Cómo usarlo: en Supabase abre "SQL Editor", pega TODO este
-- archivo y pulsa "Run".
--
-- Sirve para un proyecto nuevo y también para uno que ya tenga
-- la versión 4 (mercado): la sección 0 borra las tablas y
-- funciones anteriores antes de crear las nuevas. Los datos de la
-- versión 4 se pierden; las cuentas de Google (Supabase Auth) se
-- conservan y cada persona completa su registro otra vez.
--
-- Arquitectura:
--   * Esta base es la fuente de verdad que comparten todos.
--   * Cada cuenta pertenece a un municipio (DIVIPOLA del DANE).
--     Cada administrador solo ve y gestiona su municipio.
--   * Cada navegador descarga lo que su cuenta puede leer (RLS) a
--     una réplica SQLite (sql.js) y consulta con SQL local.
--   * Nadie escribe directamente en las tablas: todas las
--     escrituras pasan por las funciones de este archivo, que
--     validan permisos y se ejecutan como una transacción.
--   * Supabase Auth verifica la firma del token de Google.
--
-- Flujo principal:
--   ciudadano solicita la recolección → el administrador la asigna
--   a un repartidor → el repartidor recoge y registra los kilos →
--   entran al inventario del centro de acopio → las empresas
--   recicladoras piden ese material al municipio.
-- ============================================================

