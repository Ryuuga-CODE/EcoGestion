-- Inicio de sesión: identifica la cuenta de Supabase Auth (Google).
create or replace function public.iniciar_sesion() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    v_uid uuid := auth.uid();
    v_jwt jsonb := auth.jwt();
    v_correo text := lower(auth.jwt() ->> 'email');
    v_meta jsonb := coalesce(auth.jwt() -> 'user_metadata', '{}'::jsonb);
    v_nombre text;
    v_foto text;
    v_sub text;
    v_id bigint;
    v_activo smallint;
    v_admin boolean;
begin
    if v_uid is null or v_correo is null then
        raise exception 'Sesión no válida. Inicia sesión de nuevo.';
    end if;
    v_nombre := coalesce(texto_limpio(v_meta ->> 'full_name'), texto_limpio(v_meta ->> 'name'), split_part(v_correo, '@', 1));
    v_foto := nullif(coalesce(v_meta ->> 'avatar_url', v_meta ->> 'picture'), '');
    if v_foto is not null and v_foto not like 'https://%' then v_foto := null; end if;
    v_sub := coalesce(v_meta ->> 'provider_id', v_meta ->> 'sub', v_uid::text);
    v_admin := exists (select 1 from correos_administradores where correo = v_correo);

    select u.id_usuario, p.activo into v_id, v_activo
      from usuarios u join perfiles p on p.id_usuario = u.id_usuario where u.auth_id = v_uid;

    if v_id is not null then
        if v_activo = 0 then
            return jsonb_build_object('estado', 'inactivo');
        end if;
        update perfiles set foto_url = coalesce(v_foto, foto_url), ultimo_acceso = ahora_bogota() where id_usuario = v_id;
        if v_admin then
            update perfiles set id_rol = (select id_rol from roles where codigo = 'administrador') where id_usuario = v_id;
            update usuarios set rol = 'Administrador' where id_usuario = v_id;
        end if;
        return jsonb_build_object('estado', 'ok', 'id_usuario', v_id);
    end if;

    if exists (select 1 from usuarios where lower(correo) = v_correo) then
        raise exception 'Ese correo ya está asociado a otra cuenta de EcoGestión.';
    end if;

    if v_admin then
        v_id := crear_cuenta_interna(v_nombre, v_correo, v_foto, v_sub, 'administrador', null, null);
        return jsonb_build_object('estado', 'ok', 'id_usuario', v_id);
    end if;

    return jsonb_build_object('estado', 'registro', 'nombre', v_nombre, 'correo', v_correo, 'foto', v_foto);
end $$;

-- Uso interno: crea usuario + perfil con un nombre único
create or replace function public.crear_cuenta_interna(
    p_nombre text, p_correo text, p_foto text, p_sub text, p_rol text, p_telefono text, p_ubicacion text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_base text := left(coalesce(texto_limpio(p_nombre), split_part(p_correo, '@', 1)), 80);
    v_nombre text;
    v_n integer := 2;
    v_id bigint;
begin
    if length(v_base) < 2 then v_base := split_part(p_correo, '@', 1); end if;
    v_nombre := v_base;
    if exists (select 1 from usuarios where lower(nombre) = lower(v_nombre)) then
        v_nombre := left(v_base || ' (' || split_part(p_correo, '@', 1) || ')', 80);
    end if;
    while exists (select 1 from usuarios where lower(nombre) = lower(v_nombre)) loop
        v_nombre := left(v_base, 74) || ' ' || v_n;
        v_n := v_n + 1;
    end loop;

    insert into usuarios (auth_id, nombre, rol, correo)
    values (auth.uid(), v_nombre, case when p_rol = 'administrador' then 'Administrador' else 'Operador' end, p_correo)
    returning id_usuario into v_id;

    insert into perfiles (id_usuario, id_rol, google_sub, foto_url, telefono, ubicacion, metodo_registro, ultimo_acceso)
    values (v_id, (select id_rol from roles where codigo = p_rol), p_sub, p_foto, p_telefono, p_ubicacion, 'google', ahora_bogota());
    return v_id;
end $$;

-- Registro de una cuenta nueva con su tipo
create or replace function public.registrar_cuenta(
    p_tipo text, p_ubicacion text, p_telefono text, p_razon_social text, p_nit text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_info jsonb;
    v_id bigint;
    v_correo text := lower(auth.jwt() ->> 'email');
    v_ubicacion text := texto_limpio(p_ubicacion);
    v_telefono text := texto_limpio(p_telefono);
    v_razon text := texto_limpio(p_razon_social);
begin
    v_info := iniciar_sesion();
    if v_info ->> 'estado' <> 'registro' then
        raise exception 'Esta cuenta ya está registrada.';
    end if;
    if p_tipo not in ('vendedor', 'comprador', 'empresa') then
        raise exception 'Selecciona un tipo de cuenta válido.';
    end if;
    if v_ubicacion is null or length(v_ubicacion) < 2 or length(v_ubicacion) > 120 then
        raise exception 'Indica tu ciudad y barrio (entre 2 y 120 caracteres).';
    end if;
    if v_telefono is not null and v_telefono !~ '^[0-9+()\s-]{7,30}$' then
        raise exception 'Escribe un teléfono válido.';
    end if;
    if p_tipo = 'empresa' and (v_razon is null or length(v_razon) not between 2 and 120) then
        raise exception 'Escribe el nombre de la empresa (entre 2 y 120 caracteres).';
    end if;

    v_id := crear_cuenta_interna(v_info ->> 'nombre', v_correo, v_info ->> 'foto',
        coalesce(auth.jwt() -> 'user_metadata' ->> 'provider_id', auth.uid()::text),
        p_tipo, v_telefono, v_ubicacion);

    if p_tipo = 'empresa' then
        insert into empresas (id_usuario, razon_social, nit, telefono, correo_contacto, ciudad)
        values (v_id, v_razon, texto_limpio(p_nit), v_telefono, v_correo, left(v_ubicacion, 80));
    end if;
    return v_id;
end $$;

create or replace function public.actualizar_perfil(p_telefono text, p_ubicacion text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('perfil.editar');
    v_telefono text := texto_limpio(p_telefono);
    v_ubicacion text := texto_limpio(p_ubicacion);
begin
    if v_ubicacion is null or length(v_ubicacion) not between 2 and 120 then
        raise exception 'Indica tu ciudad y barrio (entre 2 y 120 caracteres).';
    end if;
    if v_telefono is not null and v_telefono !~ '^[0-9+()\s-]{7,30}$' then
        raise exception 'Escribe un teléfono válido.';
    end if;
    update perfiles set telefono = v_telefono, ubicacion = v_ubicacion where id_usuario = v_yo;
end $$;

