-- 5. Triggers de integridad (protegen la base aunque falle la app)
-- ------------------------------------------------------------
create or replace function public.trg_movimiento_validar() returns trigger
language plpgsql set search_path = public as $$
declare
    v_unidad text;
    v_existencia numeric;
begin
    select unidad_medida into v_unidad from materiales where id_material = new.id_material;
    if v_unidad is distinct from new.unidad_medida then
        raise exception 'La unidad de medida no coincide con la del material.';
    end if;
    if new.tipo = 'Salida' then
        select coalesce(sum(case when tipo = 'Entrada' then cantidad else -cantidad end), 0)
          into v_existencia from movimientos where id_material = new.id_material;
        if new.cantidad > v_existencia + 0.000001 then
            raise exception 'Stock insuficiente para registrar la salida.';
        end if;
    end if;
    return new;
end $$;
create trigger trg_movimiento_validar before insert on public.movimientos
    for each row execute function public.trg_movimiento_validar();

create or replace function public.trg_oferta_estado() returns trigger
language plpgsql set search_path = public as $$
begin
    if new.estado <> old.estado and not (
           (old.estado = 'Pendiente' and new.estado in ('Aceptada', 'Rechazada', 'Cancelada'))
        or (old.estado = 'Aceptada'  and new.estado in ('Completada', 'Cancelada'))) then
        raise exception 'Cambio de estado de la oferta no permitido.';
    end if;
    return new;
end $$;
create trigger trg_oferta_estado before update of estado on public.ofertas
    for each row execute function public.trg_oferta_estado();

