-- ============================================================
-- EcoGestión · Base central en Supabase (PostgreSQL)
-- ============================================================
-- Cómo usarlo: en Supabase abre "SQL Editor", pega TODO este
-- archivo y pulsa "Run". Se puede ejecutar una sola vez en un
-- proyecto nuevo.
--
-- Arquitectura:
--   * Esta base es la fuente de verdad que comparten todos.
--   * Cada navegador descarga lo que su rol puede leer (RLS) a una
--     réplica SQLite (sql.js) y consulta con SQL local.
--   * Nadie escribe directamente en las tablas: todas las
--     escrituras pasan por las funciones de este archivo, que
--     validan permisos y se ejecutan como una transacción.
--   * Supabase Auth verifica la firma del token de Google.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Catálogo de roles y permisos
-- ------------------------------------------------------------
create table public.roles (
    id_rol       bigint generated by default as identity primary key,
    codigo       text not null unique
                 check (codigo in ('administrador', 'vendedor', 'comprador', 'empresa')),
    nombre       text not null unique,
    descripcion  text not null
);

create table public.permisos (
    id_permiso   bigint generated by default as identity primary key,
    codigo       text not null unique,
    descripcion  text not null
);

create table public.roles_permisos (
    id_rol      bigint not null references public.roles (id_rol) on update cascade on delete cascade,
    id_permiso  bigint not null references public.permisos (id_permiso) on update cascade on delete cascade,
    primary key (id_rol, id_permiso)
);

-- Correos de Google que entran como Administrador (se administra desde el SQL Editor)
create table public.correos_administradores (
    correo text primary key check (correo = lower(btrim(correo)) and correo like '%_@_%')
);

-- ------------------------------------------------------------
-- 2. Usuarios y perfiles
-- ------------------------------------------------------------
create table public.usuarios (
    id_usuario      bigint generated by default as identity primary key,
    auth_id         uuid unique references auth.users (id) on delete set null,
    nombre          text not null check (length(btrim(nombre)) between 2 and 80),
    rol             text not null default 'Operador' check (rol in ('Administrador', 'Operador')),
    correo          text,
    fecha_registro  timestamp not null default (now() at time zone 'America/Bogota')
);
create unique index ux_usuarios_nombre on public.usuarios (lower(nombre));
create unique index ux_usuarios_correo on public.usuarios (lower(correo)) where correo is not null;

create table public.perfiles (
    id_usuario       bigint primary key references public.usuarios (id_usuario) on update cascade on delete restrict,
    id_rol           bigint not null references public.roles (id_rol) on update cascade on delete restrict,
    google_sub       text unique,
    foto_url         text check (foto_url is null or foto_url like 'https://%'),
    telefono         text check (telefono is null or length(telefono) <= 30),
    ubicacion        text check (ubicacion is null or length(ubicacion) <= 120),
    activo           smallint not null default 1 check (activo in (0, 1)),
    metodo_registro  text not null default 'google' check (metodo_registro in ('google', 'demo')),
    fecha_creacion   timestamp not null default (now() at time zone 'America/Bogota'),
    ultimo_acceso    timestamp,
    constraint chk_perfil_google check (metodo_registro <> 'google' or google_sub is not null)
);
create index idx_perfiles_rol on public.perfiles (id_rol);

