-- Inicio de sesión: identifica la cuenta de Supabase Auth (Google).
-- estado: ok | registro | pendiente | inactivo
create or replace function public.iniciar_sesion() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    v_uid uuid := auth.uid();
    v_correo text := lower(auth.jwt() ->> 'email');
    v_meta jsonb := coalesce(auth.jwt() -> 'user_metadata', '{}'::jsonb);
    v_nombre text;
    v_foto text;
    v_id bigint;
    v_activo smallint;
    v_pendiente smallint;
    v_admin boolean;
begin
    if v_uid is null or v_correo is null then
        raise exception 'Sesión no válida. Inicia sesión de nuevo.';
    end if;
    v_nombre := coalesce(texto_limpio(v_meta ->> 'full_name'), texto_limpio(v_meta ->> 'name'), split_part(v_correo, '@', 1));
    v_foto := nullif(coalesce(v_meta ->> 'avatar_url', v_meta ->> 'picture'), '');
    if v_foto is not null and v_foto not like 'https://%' then v_foto := null; end if;
    v_admin := exists (select 1 from correos_administradores where correo = v_correo);

    select u.id_usuario, p.activo, p.pendiente into v_id, v_activo, v_pendiente
      from usuarios u join perfiles p on p.id_usuario = u.id_usuario where u.auth_id = v_uid;

    if v_id is not null then
        if v_admin and v_activo = 0 then
            update perfiles set activo = 1, pendiente = 0 where id_usuario = v_id;
            v_activo := 1;
        end if;
        if v_activo = 0 then
            return jsonb_build_object('estado', case when v_pendiente = 1 then 'pendiente' else 'inactivo' end);
        end if;
        update perfiles set foto_url = coalesce(v_foto, foto_url), ultimo_acceso = ahora_bogota() where id_usuario = v_id;
        if v_admin then
            update perfiles set id_rol = (select id_rol from roles where codigo = 'administrador') where id_usuario = v_id;
            update usuarios set rol = 'Administrador' where id_usuario = v_id;
        end if;
        return jsonb_build_object('estado', 'ok', 'id_usuario', v_id);
    end if;

    if exists (select 1 from usuarios where lower(correo) = v_correo) then
        raise exception 'Ese correo ya está asociado a otra cuenta de EcoGestión.';
    end if;
    return jsonb_build_object('estado', 'registro', 'nombre', v_nombre, 'correo', v_correo,
                              'foto', v_foto, 'administrador', v_admin);
end $$;

-- Uso interno: crea usuario + perfil con un nombre único
create or replace function public.crear_cuenta_interna(
    p_nombre text, p_correo text, p_foto text, p_sub text, p_rol text,
    p_municipio text, p_telefono text, p_direccion text, p_pendiente boolean
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_base text := left(coalesce(texto_limpio(p_nombre), split_part(p_correo, '@', 1)), 80);
    v_nombre text;
    v_n integer := 2;
    v_id bigint;
begin
    if length(v_base) < 2 then v_base := split_part(p_correo, '@', 1); end if;
    v_nombre := v_base;
    if exists (select 1 from usuarios where lower(nombre) = lower(v_nombre)) then
        v_nombre := left(v_base || ' (' || split_part(p_correo, '@', 1) || ')', 80);
    end if;
    while exists (select 1 from usuarios where lower(nombre) = lower(v_nombre)) loop
        v_nombre := left(v_base, 74) || ' ' || v_n;
        v_n := v_n + 1;
    end loop;

    insert into usuarios (auth_id, nombre, rol, correo)
    values (auth.uid(), v_nombre, case when p_rol = 'administrador' then 'Administrador' else 'Operador' end, p_correo)
    returning id_usuario into v_id;

    insert into perfiles (id_usuario, id_rol, codigo_municipio, google_sub, foto_url, telefono, direccion,
                          activo, pendiente, ultimo_acceso)
    values (v_id, (select id_rol from roles where codigo = p_rol), p_municipio, p_sub, p_foto, p_telefono, p_direccion,
            case when p_pendiente then 0 else 1 end, case when p_pendiente then 1 else 0 end, ahora_bogota());
    return v_id;
end $$;

-- Registro de una cuenta nueva: tipo y municipio.
-- Las cuentas de repartidor quedan pendientes hasta que el administrador del municipio las apruebe.
create or replace function public.registrar_cuenta(
    p_tipo text, p_codigo_municipio text, p_direccion text, p_telefono text, p_razon_social text, p_nit text
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
    v_info jsonb;
    v_id bigint;
    v_tipo text := p_tipo;
    v_correo text := lower(auth.jwt() ->> 'email');
    v_direccion text := texto_limpio(p_direccion);
    v_telefono text := texto_limpio(p_telefono);
    v_razon text := texto_limpio(p_razon_social);
    v_pendiente boolean;
begin
    v_info := iniciar_sesion();
    if v_info ->> 'estado' <> 'registro' then
        raise exception 'Esta cuenta ya está registrada.';
    end if;
    if (v_info ->> 'administrador')::boolean then
        v_tipo := 'administrador';
    elsif v_tipo not in ('ciudadano', 'repartidor', 'empresa') then
        raise exception 'Selecciona un tipo de cuenta válido.';
    end if;
    if not exists (select 1 from municipios where codigo = p_codigo_municipio) then
        raise exception 'Selecciona tu departamento y municipio.';
    end if;
    if v_tipo = 'ciudadano' and (v_direccion is null or length(v_direccion) < 5) then
        raise exception 'Escribe tu dirección y barrio para las recolecciones (mínimo 5 caracteres).';
    end if;
    if v_direccion is not null and length(v_direccion) > 150 then
        raise exception 'La dirección no puede superar 150 caracteres.';
    end if;
    if v_telefono is not null and v_telefono !~ '^[0-9+()\s-]{7,30}$' then
        raise exception 'Escribe un teléfono válido.';
    end if;
    if v_tipo = 'repartidor' and v_telefono is null then
        raise exception 'Los repartidores deben indicar un teléfono de contacto.';
    end if;
    if v_tipo = 'empresa' and (v_razon is null or length(v_razon) not between 2 and 120) then
        raise exception 'Escribe el nombre de la empresa (entre 2 y 120 caracteres).';
    end if;

    v_pendiente := v_tipo = 'repartidor';
    v_id := crear_cuenta_interna(v_info ->> 'nombre', v_correo, v_info ->> 'foto',
        coalesce(auth.jwt() -> 'user_metadata' ->> 'provider_id', auth.uid()::text),
        v_tipo, p_codigo_municipio, v_telefono, v_direccion, v_pendiente);

    if v_tipo = 'empresa' then
        insert into empresas (id_usuario, razon_social, nit, telefono, correo_contacto, direccion)
        values (v_id, v_razon, texto_limpio(p_nit), v_telefono, v_correo, v_direccion);
    end if;
    return jsonb_build_object('estado', case when v_pendiente then 'pendiente' else 'ok' end, 'id_usuario', v_id);
end $$;

create or replace function public.actualizar_perfil(p_telefono text, p_direccion text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('perfil.editar');
    v_telefono text := texto_limpio(p_telefono);
    v_direccion text := texto_limpio(p_direccion);
begin
    if tiene_permiso('solicitudes.crear') and (v_direccion is null or length(v_direccion) < 5) then
        raise exception 'Escribe tu dirección y barrio (mínimo 5 caracteres).';
    end if;
    if v_direccion is not null and length(v_direccion) > 150 then
        raise exception 'La dirección no puede superar 150 caracteres.';
    end if;
    if v_telefono is not null and v_telefono !~ '^[0-9+()\s-]{7,30}$' then
        raise exception 'Escribe un teléfono válido.';
    end if;
    if tiene_permiso('recolecciones.realizar') and v_telefono is null then
        raise exception 'Los repartidores deben tener un teléfono de contacto.';
    end if;
    update perfiles set telefono = v_telefono, direccion = v_direccion where id_usuario = v_yo;
end $$;

-- ---------------------- Centro de acopio ----------------------
create or replace function public.guardar_material(
    p_id bigint, p_nombre text, p_categoria text, p_unidad text, p_descripcion text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_municipio text;
    v_nombre text := texto_limpio(p_nombre);
    v_actual materiales%rowtype;
    v_id bigint;
begin
    perform exigir('inventario.gestionar');
    v_municipio := mi_municipio();
    if v_nombre is null or length(v_nombre) not between 2 and 80 then
        raise exception 'El nombre debe tener entre 2 y 80 caracteres.';
    end if;
    if exists (select 1 from materiales where codigo_municipio = v_municipio and lower(nombre) = lower(v_nombre)
               and id_material <> coalesce(p_id, 0)) then
        raise exception 'Ya existe un material con este nombre.';
    end if;
    if p_id is null then
        insert into materiales (codigo_municipio, nombre, categoria, unidad_medida, descripcion)
        values (v_municipio, v_nombre, p_categoria, p_unidad, texto_limpio(p_descripcion)) returning id_material into v_id;
        return v_id;
    end if;
    select * into v_actual from materiales where id_material = p_id and codigo_municipio = v_municipio for update;
    if not found then raise exception 'El material ya no existe.'; end if;
    if v_actual.unidad_medida <> p_unidad and exists (select 1 from movimientos where id_material = p_id) then
        raise exception 'No puedes cambiar la unidad porque el material ya tiene movimientos.';
    end if;
    update materiales set nombre = v_nombre, categoria = p_categoria, unidad_medida = p_unidad,
           descripcion = texto_limpio(p_descripcion) where id_material = p_id;
    return p_id;
end $$;

create or replace function public.eliminar_material(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
    perform exigir('inventario.gestionar');
    if not exists (select 1 from materiales where id_material = p_id and codigo_municipio = mi_municipio()) then
        raise exception 'El material ya no existe.';
    end if;
    if exists (select 1 from movimientos where id_material = p_id)
       or exists (select 1 from recolecciones where id_material = p_id)
       or exists (select 1 from pedidos_empresa where id_material = p_id) then
        raise exception 'No se puede eliminar: el material tiene movimientos o pedidos asociados.';
    end if;
    delete from materiales where id_material = p_id;
end $$;

-- Responsable válido: cuenta activa del municipio que opera (administrador o repartidor)
create or replace function public.validar_responsable(p_id bigint, p_municipio text) returns void
language plpgsql stable security definer set search_path = public as $$
begin
    if not exists (select 1 from perfiles p join roles r on r.id_rol = p.id_rol
                   where p.id_usuario = p_id and p.activo = 1 and p.codigo_municipio = p_municipio
                     and r.codigo in ('administrador', 'repartidor')) then
        raise exception 'Selecciona un responsable válido.';
    end if;
end $$;

-- Recolección registrada directamente en el centro de acopio (sin solicitud)
create or replace function public.registrar_recoleccion(
    p_id_material bigint, p_id_responsable bigint, p_cantidad numeric, p_fecha date, p_observaciones text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_municipio text;
    v_unidad text;
    v_id bigint;
begin
    perform exigir('inventario.gestionar');
    v_municipio := mi_municipio();
    select unidad_medida into v_unidad from materiales where id_material = p_id_material and codigo_municipio = v_municipio;
    if v_unidad is null then raise exception 'El material seleccionado ya no existe.'; end if;
    perform validar_responsable(p_id_responsable, v_municipio);
    if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
    if p_fecha is null or p_fecha > hoy_bogota() then raise exception 'La fecha no puede ser futura.'; end if;

    insert into recolecciones (codigo_municipio, id_material, id_usuario, cantidad, unidad_medida, fecha, observaciones)
    values (v_municipio, p_id_material, p_id_responsable, round(p_cantidad, 2), v_unidad, p_fecha, texto_limpio(p_observaciones))
    returning id_recoleccion into v_id;
    insert into movimientos (codigo_municipio, id_material, id_recoleccion, id_usuario, tipo, cantidad, unidad_medida, fecha, observaciones)
    values (v_municipio, p_id_material, v_id, p_id_responsable, 'Entrada', round(p_cantidad, 2), v_unidad, p_fecha, texto_limpio(p_observaciones));
    return v_id;
end $$;

create or replace function public.registrar_salida(
    p_id_material bigint, p_id_responsable bigint, p_cantidad numeric, p_fecha date, p_observaciones text
) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_municipio text;
    v_unidad text;
    v_libre numeric;
begin
    perform exigir('inventario.gestionar');
    v_municipio := mi_municipio();
    select unidad_medida into v_unidad from materiales
     where id_material = p_id_material and codigo_municipio = v_municipio for update;
    if v_unidad is null then raise exception 'El material seleccionado ya no existe.'; end if;
    perform validar_responsable(p_id_responsable, v_municipio);
    if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
    if p_fecha is null or p_fecha > hoy_bogota() then raise exception 'La fecha no puede ser futura.'; end if;
    if texto_limpio(p_observaciones) is null then raise exception 'Indica el motivo o destino de la salida.'; end if;
    v_libre := existencia_material(p_id_material) - comprometido_material(p_id_material);
    if p_cantidad > v_libre + 0.000001 and comprometido_material(p_id_material) > 0 then
        raise exception 'Solo hay % % libres: el resto está reservado para pedidos de empresas aprobados.',
            cantidad_texto(v_libre), v_unidad;
    end if;
    insert into movimientos (codigo_municipio, id_material, id_recoleccion, id_usuario, tipo, cantidad, unidad_medida, fecha, observaciones)
    values (v_municipio, p_id_material, null, p_id_responsable, 'Salida', round(p_cantidad, 2), v_unidad, p_fecha, texto_limpio(p_observaciones));
end $$;

-- ------------------------ Solicitudes de recolección ------------------------
create or replace function public.crear_solicitud(
    p_direccion text, p_tipos text[], p_descripcion text, p_cantidad_estimada numeric,
    p_fecha_preferida date, p_franja text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('solicitudes.crear');
    v_direccion text := texto_limpio(p_direccion);
    v_tipos text[];
    v_id bigint;
begin
    if v_direccion is null or length(v_direccion) not between 5 and 150 then
        raise exception 'Escribe la dirección de recolección (entre 5 y 150 caracteres).';
    end if;
    select array_agg(distinct t order by t) into v_tipos from unnest(coalesce(p_tipos, '{}')) t;
    if coalesce(array_length(v_tipos, 1), 0) = 0 then
        raise exception 'Marca al menos un tipo de residuo.';
    end if;
    if not v_tipos <@ array['Plástico', 'Papel y cartón', 'Vidrio', 'Metal', 'Otros'] then
        raise exception 'Hay un tipo de residuo no válido.';
    end if;
    if p_cantidad_estimada is not null and (p_cantidad_estimada <= 0 or p_cantidad_estimada > 5000) then
        raise exception 'La cantidad estimada debe estar entre 0 y 5.000 kg.';
    end if;
    if p_fecha_preferida is null or p_fecha_preferida < hoy_bogota() or p_fecha_preferida > hoy_bogota() + 60 then
        raise exception 'Elige una fecha entre hoy y los próximos 60 días.';
    end if;
    if p_franja not in ('Mañana', 'Tarde', 'Cualquier hora') then
        raise exception 'Selecciona una franja horaria válida.';
    end if;
    if (select count(*) from solicitudes_recoleccion where id_ciudadano = v_yo and estado in ('Pendiente', 'Asignada')) >= 3 then
        raise exception 'Ya tienes 3 solicitudes abiertas. Espera a que se atiendan antes de crear otra.';
    end if;
    insert into solicitudes_recoleccion (codigo_municipio, id_ciudadano, direccion, tipos_residuo, descripcion,
                                         cantidad_estimada, fecha_preferida, franja)
    values (mi_municipio(), v_yo, v_direccion, array_to_string(v_tipos, ', '), texto_limpio(p_descripcion),
            round(p_cantidad_estimada, 2), p_fecha_preferida, p_franja)
    returning id_solicitud into v_id;
    return v_id;
end $$;

-- El ciudadano cancela la suya; el administrador del municipio también puede cancelar.
create or replace function public.cancelar_solicitud(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := yo();
    v_sol solicitudes_recoleccion%rowtype;
begin
    select * into v_sol from solicitudes_recoleccion where id_solicitud = p_id for update;
    if not found then raise exception 'La solicitud ya no existe.'; end if;
    if not ((v_sol.id_ciudadano = v_yo and tiene_permiso('solicitudes.crear'))
            or es_admin_de(v_sol.codigo_municipio, 'solicitudes.gestionar')) then
        raise exception 'No tienes permiso para realizar esta acción.';
    end if;
    if v_sol.estado not in ('Pendiente', 'Asignada') then
        raise exception 'La solicitud ya fue atendida o cerrada.';
    end if;
    update solicitudes_recoleccion set estado = 'Cancelada', nota = texto_limpio(p_motivo), fecha_cierre = ahora_bogota()
     where id_solicitud = p_id;
end $$;

create or replace function public.asignar_solicitud(p_id bigint, p_id_repartidor bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_sol solicitudes_recoleccion%rowtype;
begin
    perform exigir('solicitudes.gestionar');
    select * into v_sol from solicitudes_recoleccion where id_solicitud = p_id for update;
    if not found or v_sol.codigo_municipio <> mi_municipio() then raise exception 'La solicitud ya no existe.'; end if;
    if v_sol.estado not in ('Pendiente', 'Asignada') then
        raise exception 'Solo se asignan solicitudes pendientes o ya asignadas.';
    end if;
    if not exists (select 1 from perfiles p join roles r on r.id_rol = p.id_rol
                   where p.id_usuario = p_id_repartidor and p.activo = 1 and r.codigo = 'repartidor'
                     and p.codigo_municipio = v_sol.codigo_municipio) then
        raise exception 'Selecciona un repartidor activo de tu municipio.';
    end if;
    update solicitudes_recoleccion
       set estado = 'Asignada', id_repartidor = p_id_repartidor, fecha_asignacion = ahora_bogota(), nota = null
     where id_solicitud = p_id;
end $$;

create or replace function public.rechazar_solicitud(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_sol solicitudes_recoleccion%rowtype;
begin
    perform exigir('solicitudes.gestionar');
    select * into v_sol from solicitudes_recoleccion where id_solicitud = p_id for update;
    if not found or v_sol.codigo_municipio <> mi_municipio() then raise exception 'La solicitud ya no existe.'; end if;
    if v_sol.estado not in ('Pendiente', 'Asignada') then raise exception 'La solicitud ya fue atendida o cerrada.'; end if;
    if texto_limpio(p_motivo) is null then raise exception 'Escribe el motivo para que el ciudadano lo vea.'; end if;
    update solicitudes_recoleccion set estado = 'Rechazada', nota = texto_limpio(p_motivo), fecha_cierre = ahora_bogota()
     where id_solicitud = p_id;
