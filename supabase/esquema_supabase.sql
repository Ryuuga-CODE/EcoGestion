create or replace function public.guardar_material(
    p_id bigint, p_nombre text, p_categoria text, p_unidad text, p_descripcion text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_nombre text := texto_limpio(p_nombre);
    v_actual materiales%rowtype;
    v_id bigint;
begin
    perform exigir('inventario.gestionar');
    if v_nombre is null or length(v_nombre) not between 2 and 80 then
        raise exception 'El nombre debe tener entre 2 y 80 caracteres.';
    end if;
    if exists (select 1 from materiales where lower(nombre) = lower(v_nombre) and id_material <> coalesce(p_id, 0)) then
        raise exception 'Ya existe un material con este nombre.';
    end if;
    if p_id is null then
        insert into materiales (nombre, categoria, unidad_medida, descripcion)
        values (v_nombre, p_categoria, p_unidad, texto_limpio(p_descripcion)) returning id_material into v_id;
        return v_id;
    end if;
    select * into v_actual from materiales where id_material = p_id for update;
