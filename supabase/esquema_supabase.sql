create policy leer_perfiles on public.perfiles for select to authenticated using (puede_ver_usuario(id_usuario));

-- Materiales del municipio: cualquiera del municipio (los repartidores registran por material)
create policy leer_materiales on public.materiales for select to authenticated
    using (codigo_municipio = mi_municipio());

-- Solicitudes: el ciudadano las suyas, el repartidor las asignadas, el administrador las del municipio
create policy leer_solicitudes on public.solicitudes_recoleccion for select to authenticated using (
    id_ciudadano = yo() or id_repartidor = yo() or es_admin_de(codigo_municipio, 'solicitudes.gestionar'));

-- Recolecciones: el administrador del municipio y el repartidor que las hizo
create policy leer_recolecciones on public.recolecciones for select to authenticated using (
    es_admin_de(codigo_municipio, 'inventario.gestionar') or id_usuario = yo());

-- Movimientos de inventario: solo el administrador del municipio
create policy leer_movimientos on public.movimientos for select to authenticated using (
    es_admin_de(codigo_municipio, 'inventario.gestionar'));

-- Empresas: la propia y el administrador de su municipio
create policy leer_empresas on public.empresas for select to authenticated using (
    id_usuario = yo() or es_admin_de(municipio_de(id_usuario), 'pedidos.gestionar'));

-- Pedidos: la empresa que lo hizo y el administrador del municipio
create policy leer_pedidos on public.pedidos_empresa for select to authenticated using (
    exists (select 1 from empresas e where e.id_empresa = pedidos_empresa.id_empresa and e.id_usuario = yo())
    or es_admin_de(codigo_municipio, 'pedidos.gestionar'));

-- correos_administradores: sin políticas = nadie lo lee desde la app.

-- Existencias públicas del municipio (las empresas ven cuánto hay sin ver los movimientos)
create view public.existencias_municipio as
select m.id_material, m.codigo_municipio, m.nombre, m.categoria, m.unidad_medida,
       existencia_material(m.id_material) as existencia,
       comprometido_material(m.id_material) as comprometido
from public.materiales m
where m.codigo_municipio = public.mi_municipio();

