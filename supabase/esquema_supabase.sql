create or replace function public.guardar_publicacion(
    p_id bigint, p_tipo text, p_nombre text, p_descripcion text, p_cantidad numeric,
    p_unidad text, p_precio numeric, p_ubicacion text, p_fotos text[]
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('publicaciones.gestionar');
    v_actual publicaciones%rowtype;
    v_unidad text := p_unidad;
    v_estado text;
    v_id bigint;
    v_i integer;
begin
    if texto_limpio(p_nombre) is null or length(texto_limpio(p_nombre)) not between 2 and 80 then
        raise exception 'El nombre debe tener entre 2 y 80 caracteres.';
    end if;
    if p_precio is null or p_precio <= 0 then raise exception 'El precio debe ser mayor que cero.'; end if;
    if p_cantidad is null or p_cantidad < 0 then raise exception 'La cantidad no puede ser negativa.'; end if;
    if coalesce(array_length(p_fotos, 1), 0) > 3 then raise exception 'Puedes agregar hasta 3 fotos.'; end if;

    if p_id is null then
        if p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
        insert into publicaciones (id_vendedor, tipo_residuo, nombre_material, descripcion,
                                   cantidad_disponible, unidad, precio_unitario, ubicacion)
        values (v_yo, p_tipo, texto_limpio(p_nombre), texto_limpio(p_descripcion), round(p_cantidad, 2),
                p_unidad, round(p_precio, 2), texto_limpio(p_ubicacion))
        returning id_publicacion into v_id;
    else
        select * into v_actual from publicaciones where id_publicacion = p_id and id_vendedor = v_yo for update;
        if not found then raise exception 'No se encontró la publicación.'; end if;
        if exists (select 1 from ofertas where id_publicacion = p_id) then v_unidad := v_actual.unidad; end if;
        v_estado := case when v_actual.estado = 'Retirada' then 'Retirada'
                         when p_cantidad > 0 then 'Activa' else 'Agotada' end;
        update publicaciones set tipo_residuo = p_tipo, nombre_material = texto_limpio(p_nombre),
               descripcion = texto_limpio(p_descripcion), cantidad_disponible = round(p_cantidad, 2),
               unidad = v_unidad, precio_unitario = round(p_precio, 2), ubicacion = texto_limpio(p_ubicacion),
               estado = v_estado, fecha_actualizacion = ahora_bogota()
         where id_publicacion = p_id;
        delete from fotos_publicacion where id_publicacion = p_id;
        v_id := p_id;
    end if;

    for v_i in 1 .. coalesce(array_length(p_fotos, 1), 0) loop
        insert into fotos_publicacion (id_publicacion, imagen, orden) values (v_id, p_fotos[v_i], v_i);
    end loop;
    return v_id;
end $$;

create or replace function public.cambiar_estado_publicacion(p_id bigint, p_accion text) returns text
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('publicaciones.gestionar');
    v_pub publicaciones%rowtype;
begin
    select * into v_pub from publicaciones where id_publicacion = p_id and id_vendedor = v_yo for update;
    if not found then raise exception 'No se encontró la publicación.'; end if;
    if p_accion = 'retirar' then
        update ofertas set estado = 'Rechazada', fecha_respuesta = ahora_bogota()
         where id_publicacion = p_id and estado = 'Pendiente';
        update publicaciones set estado = 'Retirada', fecha_actualizacion = ahora_bogota() where id_publicacion = p_id;
        return 'Retirada';
    elsif p_accion = 'reactivar' then
        update publicaciones set estado = case when cantidad_disponible > 0 then 'Activa' else 'Agotada' end,
               fecha_actualizacion = ahora_bogota() where id_publicacion = p_id;
        return (select estado from publicaciones where id_publicacion = p_id);
    end if;
    raise exception 'Acción no válida.';
end $$;

create or replace function public.eliminar_publicacion(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('publicaciones.gestionar');
begin
    if not exists (select 1 from publicaciones where id_publicacion = p_id and id_vendedor = v_yo) then
        raise exception 'No se encontró la publicación.';
    end if;
    if exists (select 1 from ofertas where id_publicacion = p_id) then
        raise exception 'No se puede eliminar: la publicación tiene ofertas asociadas. Puedes retirarla.';
    end if;
    delete from publicaciones where id_publicacion = p_id;
