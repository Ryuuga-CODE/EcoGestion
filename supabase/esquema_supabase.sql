create or replace function public.admin_estado_usuario(p_id bigint, p_activo boolean) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('usuarios.gestionar');
begin
    if p_id = v_yo then raise exception 'No puedes desactivar tu propia cuenta.'; end if;
    if not p_activo and exists (select 1 from perfiles p join roles r on r.id_rol = p.id_rol
                                 where p.id_usuario = p_id and r.codigo = 'administrador' and p.activo = 1)
       and (select count(*) from perfiles p join roles r on r.id_rol = p.id_rol
             where r.codigo = 'administrador' and p.activo = 1) <= 1 then
        raise exception 'Debe quedar al menos un administrador activo.';
    end if;
    update perfiles set activo = case when p_activo then 1 else 0 end where id_usuario = p_id;
    if not found then raise exception 'La cuenta no existe.'; end if;
end $$;

create or replace function public.admin_rol_usuario(p_id bigint, p_rol text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('usuarios.gestionar');
    v_actual text;
begin
    if p_id = v_yo then raise exception 'No puedes cambiar el tipo de tu propia cuenta.'; end if;
    select r.codigo into v_actual from perfiles p join roles r on r.id_rol = p.id_rol where p.id_usuario = p_id;
    if v_actual is null then raise exception 'La cuenta no existe.'; end if;
    if not exists (select 1 from roles where codigo = p_rol) then raise exception 'Tipo de cuenta no válido.'; end if;
    if v_actual = 'administrador' and p_rol <> 'administrador'
       and (select count(*) from perfiles p join roles r on r.id_rol = p.id_rol
             where r.codigo = 'administrador' and p.activo = 1) <= 1 then
        raise exception 'Debe quedar al menos un administrador activo.';
    end if;
    update perfiles set id_rol = (select id_rol from roles where codigo = p_rol) where id_usuario = p_id;
    update usuarios set rol = case when p_rol = 'administrador' then 'Administrador' else 'Operador' end where id_usuario = p_id;
    if v_actual = 'vendedor' and p_rol <> 'vendedor' then
        update ofertas set estado = 'Rechazada', fecha_respuesta = ahora_bogota()
         where estado = 'Pendiente'
           and id_publicacion in (select id_publicacion from publicaciones where id_vendedor = p_id);
    end if;
end $$;

