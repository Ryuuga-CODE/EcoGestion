-- El repartidor no pudo recogerla: vuelve a quedar pendiente para reasignar
create or replace function public.devolver_solicitud(p_id bigint, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('recolecciones.realizar');
    v_sol solicitudes_recoleccion%rowtype;
begin
    select * into v_sol from solicitudes_recoleccion where id_solicitud = p_id for update;
    if not found or v_sol.id_repartidor is distinct from v_yo then raise exception 'La solicitud no está asignada a ti.'; end if;
    if v_sol.estado <> 'Asignada' then raise exception 'La solicitud ya no está asignada.'; end if;
    if texto_limpio(p_motivo) is null then raise exception 'Cuenta brevemente por qué no se pudo recoger.'; end if;
    update solicitudes_recoleccion set estado = 'Pendiente', id_repartidor = null, fecha_asignacion = null,
           nota = texto_limpio(p_motivo)
     where id_solicitud = p_id;
end $$;

-- Recolección hecha: p_detalle = [{"id_material": 1, "cantidad": 12.5}, ...]
-- Crea una recolección y su entrada al inventario por cada material.
create or replace function public.completar_solicitud(p_id bigint, p_detalle jsonb, p_observaciones text) returns numeric
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := yo();
    v_sol solicitudes_recoleccion%rowtype;
    v_item jsonb;
    v_material materiales%rowtype;
    v_cantidad numeric;
    v_id_rec bigint;
    v_kilos numeric := 0;
    v_vistos bigint[] := '{}';
    v_obs text := texto_limpio(p_observaciones);
begin
    select * into v_sol from solicitudes_recoleccion where id_solicitud = p_id for update;
    if not found then raise exception 'La solicitud ya no existe.'; end if;
    if not ((v_sol.id_repartidor = v_yo and tiene_permiso('recolecciones.realizar'))
            or es_admin_de(v_sol.codigo_municipio, 'solicitudes.gestionar')) then
        raise exception 'La solicitud no está asignada a ti.';
    end if;
    if v_sol.estado <> 'Asignada' then raise exception 'Solo se completan solicitudes asignadas.'; end if;
    if jsonb_typeof(p_detalle) <> 'array' or jsonb_array_length(p_detalle) = 0 then
        raise exception 'Registra al menos un material con su cantidad.';
    end if;

    for v_item in select * from jsonb_array_elements(p_detalle) loop
        select * into v_material from materiales
         where id_material = (v_item ->> 'id_material')::bigint and codigo_municipio = v_sol.codigo_municipio;
        if not found then raise exception 'Uno de los materiales no existe en el centro de acopio.'; end if;
        if v_material.id_material = any (v_vistos) then
            raise exception 'El material % está repetido.', v_material.nombre;
        end if;
        v_vistos := v_vistos || v_material.id_material;
        v_cantidad := round((v_item ->> 'cantidad')::numeric, 2);
        if v_cantidad is null or v_cantidad <= 0 then raise exception 'Cada cantidad debe ser mayor que cero.'; end if;
        if v_material.unidad_medida = 'unidades' and v_cantidad <> trunc(v_cantidad) then
            raise exception 'Para % la cantidad debe ser un número entero.', v_material.nombre;
        end if;

        insert into recolecciones (codigo_municipio, id_material, id_usuario, id_solicitud, cantidad, unidad_medida, fecha, observaciones)
        values (v_sol.codigo_municipio, v_material.id_material, v_sol.id_repartidor, p_id, v_cantidad,
                v_material.unidad_medida, hoy_bogota(), coalesce(v_obs, 'Solicitud #' || p_id))
        returning id_recoleccion into v_id_rec;
        insert into movimientos (codigo_municipio, id_material, id_recoleccion, id_usuario, tipo, cantidad, unidad_medida, fecha, observaciones)
        values (v_sol.codigo_municipio, v_material.id_material, v_id_rec, v_sol.id_repartidor, 'Entrada', v_cantidad,
                v_material.unidad_medida, hoy_bogota(), 'Solicitud #' || p_id);
        if v_material.unidad_medida = 'kg' then v_kilos := v_kilos + v_cantidad; end if;
    end loop;

    update solicitudes_recoleccion
       set estado = 'Recolectada', kilos_recolectados = v_kilos, nota = v_obs, fecha_cierre = ahora_bogota()
     where id_solicitud = p_id;
    return v_kilos;
end $$;

-- ------------------------ Empresas y pedidos ------------------------
create or replace function public.guardar_empresa(
    p_razon_social text, p_nit text, p_telefono text, p_correo text, p_direccion text, p_descripcion text
) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('empresa.gestionar');
begin
    if texto_limpio(p_razon_social) is null or length(texto_limpio(p_razon_social)) not between 2 and 120 then
        raise exception 'Escribe el nombre de la empresa (entre 2 y 120 caracteres).';
    end if;
    insert into empresas (id_usuario, razon_social, nit, telefono, correo_contacto, direccion, descripcion)
    values (v_yo, texto_limpio(p_razon_social), texto_limpio(p_nit), texto_limpio(p_telefono), texto_limpio(p_correo),
            texto_limpio(p_direccion), nullif(btrim(coalesce(p_descripcion, '')), ''))
    on conflict (id_usuario) do update set
        razon_social = excluded.razon_social, nit = excluded.nit, telefono = excluded.telefono,
        correo_contacto = excluded.correo_contacto, direccion = excluded.direccion, descripcion = excluded.descripcion;
end $$;

create or replace function public.crear_pedido(
    p_id_material bigint, p_cantidad numeric, p_precio numeric, p_mensaje text
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('pedidos.crear');
    v_empresa bigint;
    v_material materiales%rowtype;
    v_libre numeric;
    v_id bigint;
begin
    select id_empresa into v_empresa from empresas where id_usuario = v_yo;
    if v_empresa is null then raise exception 'Primero completa el perfil empresarial.'; end if;
    select * into v_material from materiales where id_material = p_id_material and codigo_municipio = mi_municipio();
    if not found then raise exception 'El material no existe en el centro de acopio de tu municipio.'; end if;
    if p_cantidad is null or p_cantidad <= 0 then raise exception 'La cantidad debe ser mayor que cero.'; end if;
    if v_material.unidad_medida = 'unidades' and p_cantidad <> trunc(p_cantidad) then
        raise exception 'Para unidades, la cantidad debe ser un número entero.';
    end if;
    v_libre := existencia_material(p_id_material) - comprometido_material(p_id_material);
    if p_cantidad > v_libre + 0.000001 then
        raise exception 'Solo hay % % disponibles de %.',
            cantidad_texto(v_libre), v_material.unidad_medida, v_material.nombre;
    end if;
    if p_precio is null or p_precio <= 0 then raise exception 'El precio debe ser mayor que cero.'; end if;
    if exists (select 1 from pedidos_empresa where id_empresa = v_empresa and id_material = p_id_material and estado = 'Pendiente') then
        raise exception 'Ya tienes un pedido pendiente de este material.';
    end if;
    insert into pedidos_empresa (codigo_municipio, id_empresa, id_material, cantidad, precio_unitario, mensaje)
    values (v_material.codigo_municipio, v_empresa, p_id_material, round(p_cantidad, 2), round(p_precio, 2), texto_limpio(p_mensaje))
    returning id_pedido into v_id;
    return v_id;
end $$;

-- Administrador: aprobar | rechazar | entregar.  Empresa: cancelar.
create or replace function public.responder_pedido(p_id bigint, p_accion text, p_respuesta text) returns text
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := yo();
    v_ped pedidos_empresa%rowtype;
    v_material materiales%rowtype;
    v_es_admin boolean;
    v_es_empresa boolean;
    v_libre numeric;
begin
    if v_yo is null then raise exception 'No tienes permiso para realizar esta acción.'; end if;
    select * into v_ped from pedidos_empresa where id_pedido = p_id for update;
    if not found then raise exception 'El pedido ya no existe.'; end if;
    select * into v_material from materiales where id_material = v_ped.id_material for update;
    v_es_admin := es_admin_de(v_ped.codigo_municipio, 'pedidos.gestionar');
    v_es_empresa := tiene_permiso('pedidos.crear')
                    and exists (select 1 from empresas where id_empresa = v_ped.id_empresa and id_usuario = v_yo);

    if p_accion = 'aprobar' then
        if not v_es_admin then raise exception 'Solo el administrador del municipio aprueba pedidos.'; end if;
        if v_ped.estado <> 'Pendiente' then raise exception 'El pedido ya no está pendiente.'; end if;
        v_libre := existencia_material(v_ped.id_material) - comprometido_material(v_ped.id_material);
        if v_ped.cantidad > v_libre + 0.000001 then
            raise exception 'No alcanza: hay % % libres de %.',
                cantidad_texto(v_libre), v_material.unidad_medida, v_material.nombre;
        end if;
        update pedidos_empresa set estado = 'Aprobado', respuesta = texto_limpio(p_respuesta), fecha_respuesta = ahora_bogota()
         where id_pedido = p_id;
        return 'Aprobado';

    elsif p_accion = 'rechazar' then
        if not v_es_admin then raise exception 'Solo el administrador del municipio rechaza pedidos.'; end if;
        if v_ped.estado not in ('Pendiente', 'Aprobado') then raise exception 'El pedido ya está cerrado.'; end if;
        if texto_limpio(p_respuesta) is null then raise exception 'Escribe el motivo para la empresa.'; end if;
        update pedidos_empresa set estado = 'Rechazado', respuesta = texto_limpio(p_respuesta), fecha_respuesta = ahora_bogota()
         where id_pedido = p_id;
        return 'Rechazado';

    elsif p_accion = 'entregar' then
        if not v_es_admin then raise exception 'Solo el administrador del municipio registra entregas.'; end if;
        if v_ped.estado <> 'Aprobado' then raise exception 'Solo se entregan pedidos aprobados.'; end if;
        insert into movimientos (codigo_municipio, id_material, id_pedido, id_usuario, tipo, cantidad, unidad_medida, fecha, observaciones)
        values (v_ped.codigo_municipio, v_ped.id_material, p_id, v_yo, 'Salida', v_ped.cantidad, v_material.unidad_medida,
                hoy_bogota(), left('Pedido #' || p_id || ' · ' || (select razon_social from empresas where id_empresa = v_ped.id_empresa), 300));
        update pedidos_empresa set estado = 'Entregado', fecha_entrega = ahora_bogota(),
               respuesta = coalesce(texto_limpio(p_respuesta), respuesta)
         where id_pedido = p_id;
        return 'Entregado';

    elsif p_accion = 'cancelar' then
        if not v_es_empresa then raise exception 'Solo la empresa que hizo el pedido puede cancelarlo.'; end if;
        if v_ped.estado not in ('Pendiente', 'Aprobado') then raise exception 'El pedido ya está cerrado.'; end if;
        update pedidos_empresa set estado = 'Cancelado', respuesta = coalesce(texto_limpio(p_respuesta), respuesta),
               fecha_respuesta = ahora_bogota()
         where id_pedido = p_id;
        return 'Cancelado';
    end if;
    raise exception 'Acción no válida.';
end $$;

-- -------------------------- Administración --------------------------
-- Activar (también aprueba repartidores pendientes) o desactivar cuentas del municipio
create or replace function public.admin_estado_usuario(p_id bigint, p_activo boolean) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('usuarios.gestionar');
    v_rol text;
begin
    if p_id = v_yo then raise exception 'No puedes desactivar tu propia cuenta.'; end if;
    if not es_admin_de(municipio_de(p_id)) then raise exception 'La cuenta no existe en tu municipio.'; end if;
    select r.codigo into v_rol from perfiles p join roles r on r.id_rol = p.id_rol where p.id_usuario = p_id;
    if not p_activo and v_rol = 'administrador'
       and (select count(*) from perfiles p join roles r on r.id_rol = p.id_rol
             where r.codigo = 'administrador' and p.activo = 1 and p.codigo_municipio = municipio_de(p_id)) <= 1 then
        raise exception 'Debe quedar al menos un administrador activo en el municipio.';
    end if;
    update perfiles set activo = case when p_activo then 1 else 0 end, pendiente = 0 where id_usuario = p_id;
    if not p_activo and v_rol = 'repartidor' then
        update solicitudes_recoleccion
           set estado = 'Pendiente', id_repartidor = null, fecha_asignacion = null,
               nota = 'El repartidor asignado ya no está disponible.'
         where id_repartidor = p_id and estado = 'Asignada';
    end if;
end $$;

-- Cambiar entre ciudadano, repartidor y administrador (las empresas se registran aparte)
create or replace function public.admin_rol_usuario(p_id bigint, p_rol text) returns void
language plpgsql security definer set search_path = public as $$
declare
    v_yo bigint := exigir('usuarios.gestionar');
    v_actual text;
begin
    if p_id = v_yo then raise exception 'No puedes cambiar el tipo de tu propia cuenta.'; end if;
    if not es_admin_de(municipio_de(p_id)) then raise exception 'La cuenta no existe en tu municipio.'; end if;
    select r.codigo into v_actual from perfiles p join roles r on r.id_rol = p.id_rol where p.id_usuario = p_id;
    if p_rol not in ('ciudadano', 'repartidor', 'administrador') then
        raise exception 'Tipo de cuenta no válido.';
    end if;
    if v_actual = 'empresa' then
        raise exception 'Las cuentas de empresa no cambian de tipo: tienen perfil empresarial y pedidos.';
    end if;
    if v_actual = 'administrador' and p_rol <> 'administrador'
       and (select count(*) from perfiles p join roles r on r.id_rol = p.id_rol
             where r.codigo = 'administrador' and p.activo = 1 and p.codigo_municipio = municipio_de(p_id)) <= 1 then
        raise exception 'Debe quedar al menos un administrador activo en el municipio.';
    end if;
    update perfiles set id_rol = (select id_rol from roles where codigo = p_rol) where id_usuario = p_id;
    update usuarios set rol = case when p_rol = 'administrador' then 'Administrador' else 'Operador' end where id_usuario = p_id;
    if v_actual = 'repartidor' and p_rol <> 'repartidor' then
        update solicitudes_recoleccion
           set estado = 'Pendiente', id_repartidor = null, fecha_asignacion = null,
               nota = 'El repartidor asignado ya no está disponible.'
         where id_repartidor = p_id and estado = 'Asignada';
    end if;
end $$;

