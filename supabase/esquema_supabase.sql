create or replace function public.yo() returns bigint
language sql stable security definer set search_path = public as $$
    select u.id_usuario from usuarios u join perfiles p on p.id_usuario = u.id_usuario
    where u.auth_id = auth.uid() and p.activo = 1
$$;

create or replace function public.mi_municipio() returns text
language sql stable security definer set search_path = public as $$
    select p.codigo_municipio from usuarios u join perfiles p on p.id_usuario = u.id_usuario
    where u.auth_id = auth.uid() and p.activo = 1
$$;

create or replace function public.municipio_de(p_id_usuario bigint) returns text
language sql stable security definer set search_path = public as $$
    select codigo_municipio from perfiles where id_usuario = p_id_usuario
$$;

create or replace function public.tiene_permiso(p_permiso text) returns boolean
language sql stable security definer set search_path = public as $$
    select exists (
        select 1 from usuarios u
        join perfiles p on p.id_usuario = u.id_usuario
        join roles_permisos rp on rp.id_rol = p.id_rol
        join permisos pe on pe.id_permiso = rp.id_permiso
        where u.auth_id = auth.uid() and p.activo = 1 and pe.codigo = p_permiso)
$$;

-- ¿Quien llama tiene el permiso y además es del municipio indicado?
create or replace function public.es_admin_de(p_municipio text, p_permiso text default 'usuarios.gestionar') returns boolean
language sql stable security definer set search_path = public as $$
    select p_municipio is not null and mi_municipio() = p_municipio and tiene_permiso(p_permiso)
$$;

create or replace function public.exigir(p_permiso text) returns bigint
language plpgsql stable security definer set search_path = public as $$
begin
    if not tiene_permiso(p_permiso) then
        raise exception 'No tienes permiso para realizar esta acción.';
    end if;
    return yo();
end $$;

-- Quién puede ver a quién: uno mismo, los administradores ven su municipio,
-- todos ven a los administradores de su municipio, y el ciudadano y el
-- repartidor de una misma solicitud se ven entre sí (para coordinar).
create or replace function public.puede_ver_usuario(p_id bigint) returns boolean
language sql stable security definer set search_path = public as $$
    select yo() is not null and (
        p_id = yo()
        or (municipio_de(p_id) = mi_municipio() and (
                tiene_permiso('usuarios.gestionar')
             or exists (select 1 from perfiles p join roles r on r.id_rol = p.id_rol
                        where p.id_usuario = p_id and r.codigo = 'administrador')))
        or exists (select 1 from solicitudes_recoleccion s
                   where (s.id_ciudadano = yo() and s.id_repartidor = p_id)
                      or (s.id_repartidor = yo() and s.id_ciudadano = p_id)))
$$;

